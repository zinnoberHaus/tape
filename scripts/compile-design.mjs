import {parseDocument} from 'htmlparser2';
import {readFileSync,writeFileSync} from 'node:fs';
const html=readFileSync('src/design/tape.html','utf8');
const doc=parseDocument(html,{xmlMode:true,decodeEntities:true});
const expr=s=>s.trim().replace(/^{{\s*|\s*}}$/g,'');
function val(s) {
 const parts=s.split(/({{[\s\S]*?}})/g).filter(Boolean);
 if(parts.length===1&&parts[0].startsWith('{{')) return expr(parts[0]);
 return parts.map(p=>p.startsWith('{{')?`(${expr(p)})`:JSON.stringify(p)).join(' + ')||'""';
}
const camel=s=>s.replace(/-([a-z])/g,(_,c)=>c.toUpperCase());
function style(s){return '{'+s.split(';').filter(x=>x.trim()).map(x=>{const i=x.indexOf(':');return JSON.stringify(camel(x.slice(0,i).trim()))+':'+val(x.slice(i+1).trim())}).join(',')+'}'}
const hover=[];
function node(n){
 if(n.type==='text') return n.data.trim()?'{'+val(n.data)+'}':null;
 if(n.type==='comment') return null;
 const kids=(n.children||[]).map(node).filter(Boolean).join('\n');
 if(n.name==='sc-if')return `{${expr(n.attribs.value)} ? <>${kids}</> : null}`;
 if(n.name==='sc-for')return `{(${expr(n.attribs.list)} || []).map((${n.attribs.as}, index) => <React.Fragment key={index}>${kids}</React.Fragment>)}`;
 if(!n.name)return kids;
 const a={...n.attribs};
 if(a.onClick&&!['button','a','input','textarea'].includes(n.name)){a.role='button';a.tabIndex='0';if(!a.onKeyDown)a.onKeyDown='{{ (event) => { if (event.key === \"Enter\" || event.key === \" \") { event.preventDefault(); ('+expr(a.onClick)+')(event); } } }}';}
 if(a['style-hover']){let c='design-hover-'+hover.length;hover.push(`.${c}:hover{${a['style-hover']}}`);a.class=(a.class||'')+' '+c;delete a['style-hover'];}
 const attrs=Object.entries(a).filter(([k])=>!k.startsWith('hint-')).map(([k,v])=>k==='style'?`style={${style(v)}}`:`${k==='class'?'className':k==='for'?'htmlFor':k}={${val(v)}}`).join(' ');
 const voids=['input','meta','link','br','hr','img'];
 return voids.includes(n.name)?`<${n.name} ${attrs} />`:`<${n.name} ${attrs}>${kids}</${n.name}>`;
}
const locals=new Set(['t']);
for(const m of html.matchAll(/{{\s*([\w$]+)(?:[\s.}]|$)/g)) locals.add(m[1]);
for(const m of html.matchAll(/as="([\w]+)"/g)) if(m[1] !== 't') locals.delete(m[1]);
locals.delete('true'); locals.delete('false');
const source=`// Generated by scripts/compile-design.mjs from the supplied v2 design.\nimport React from 'react';\nexport default function TapeView(values) {\nconst {${[...locals].join(',')}}=values;\nreturn <>${doc.children.map(node).join('\n')}</>;\n}\n`;
writeFileSync('src/components/tape-view.jsx',source);
writeFileSync('src/design/hover.css',hover.join('\n'));
console.log('Compiled v2 design to React: '+locals.size+' bindings');
